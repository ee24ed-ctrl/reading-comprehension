// توليد IDs تلقائياً
export const TRAINING_EXERCISES: TrainingExercise[] = RAW_TRAININGS.map((t, idx) => ({
  ...t,
  id: `training_${idx + 1}`,
}));

// جلب التدريبات حسب المرحلة
export function getTrainingsByStage(stage: StageKey): TrainingExercise[] {
  return TRAINING_EXERCISES.filter((t) => t.stage === stage);
}

// جلب التدريبات حسب المرحلة والمهارة
export function getTrainingsBySkill(stage: StageKey, skill: SkillKey): TrainingExercise[] {
  return TRAINING_EXERCISES.filter((t) => t.stage === stage && t.skill === skill);
}

// جلب التدريبات حسب المرحلة والمهارة والمستوى
export function getTrainingsByLevel(
  stage: StageKey,
  skill: SkillKey,
  level: 1 | 2 | 3
): TrainingExercise | undefined {
  return TRAINING_EXERCISES.find((t) => t.stage === stage && t.skill === skill && t.level === level);
}

// إحصائيات التدريبات
export function getTrainingStats() {
  return {
    total: TRAINING_EXERCISES.length,
    byStage: {
      primary_lower: TRAINING_EXERCISES.filter((t) => t.stage === "primary_lower").length,
      primary_upper: TRAINING_EXERCISES.filter((t) => t.stage === "primary_upper").length,
      intermediate: TRAINING_EXERCISES.filter((t) => t.stage === "intermediate").length,
      secondary: TRAINING_EXERCISES.filter((t) => t.stage === "secondary").length,
    },
  };
}
