// جلب جميع اختبارات نافس لمرحلة معينة
export function getNafesExamsByStage(stage: StageKey): NafesExam[] {
  return NAFES_EXAMS.filter((e) => e.stage === stage);
}

// جلب اختبار نافس بواسطة ID
export function getNafesExamById(id: string): NafesExam | undefined {
  return NAFES_EXAMS.find((e) => e.id === id);
}

// جلب إحصائيات اختبارات نافس
export function getNafesExamsStats() {
  return {
    totalExams: NAFES_EXAMS.length,
    byStage: {
      primary_lower: NAFES_EXAMS.filter((e) => e.stage === "primary_lower").length,
      primary_upper: NAFES_EXAMS.filter((e) => e.stage === "primary_upper").length,
      intermediate: NAFES_EXAMS.filter((e) => e.stage === "intermediate").length,
      secondary: NAFES_EXAMS.filter((e) => e.stage === "secondary").length,
    },
    totalQuestions: NAFES_EXAMS.reduce((acc, curr) => acc + curr.questions.length, 0),
  };
}
