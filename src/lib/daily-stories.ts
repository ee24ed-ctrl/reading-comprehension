export function getStoriesByStage(stage: string): DailyStory[] {
  return DAILY_STORIES.filter((s) => s.stage === stage);
}

export function getStoryById(id: string): DailyStory | undefined {
  return DAILY_STORIES.find((s) => s.id === id);
}

export function getTodayStoryForUser(stage: string, daySeedOffset = 0): DailyStory {
  const stageStories = getStoriesByStage(stage);
  if (stageStories.length === 0) return DAILY_STORIES[0];
  const now = new Date();
  const dayOfYear = Math.floor(
    (now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  const index = (dayOfYear + daySeedOffset) % stageStories.length;
  return stageStories[index];
}

